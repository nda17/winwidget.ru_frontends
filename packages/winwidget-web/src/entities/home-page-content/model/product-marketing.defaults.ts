// Only keys present in the trusted editorial template may reach the UI.
// Old stored documents can omit either page or any newly introduced section.
export function marketingTextLimit(key: string): number {
	if (key === 'keywords') return 200
	return [
		'title',
		'ogTitle',
		'eyebrow',
		'buttonText',
		'widgetsButtonText',
		'crmButtonText'
	].includes(key)
		? 500
		: 2000
}

export function normalizeMarketingContent<T>(
	value: unknown,
	fallback: T,
	key = ''
): T {
	if (typeof fallback === 'string') {
		return (
			typeof value === 'string' && value.length <= marketingTextLimit(key)
				? value
				: fallback
		) as T
	}
	if (typeof fallback === 'boolean') {
		return (typeof value === 'boolean' ? value : fallback) as T
	}
	if (Array.isArray(fallback)) {
		return (
			Array.isArray(value)
				? value
						.slice(0, 50)
						.map((item, index) =>
							normalizeMarketingContent(
								item,
								fallback[index] ?? fallback[0],
								key
							)
						)
				: structuredClone(fallback)
		) as T
	}
	const source =
		value && typeof value === 'object' && !Array.isArray(value)
			? (value as Record<string, unknown>)
			: {}
	return Object.fromEntries(
		Object.entries(fallback as Record<string, unknown>).map(
			([fieldKey, defaultValue]) => [
				fieldKey,
				normalizeMarketingContent(source[fieldKey], defaultValue, fieldKey)
			]
		)
	) as T
}
